from pathlib import Path


def load_testcases(filename):

    testcases = {}

    current_dim = None
    current_case = None

    with open(filename, "r", encoding="utf-8") as f:

        for raw_line in f:

            line = raw_line.strip().rstrip(",")

            if not line:
                continue

            # 5-bit
            if "-bit" in line:

                dim = int(line.split("-")[0])

                current_dim = f"{dim}d"

                testcases[current_dim] = []

                current_case = None

                continue

            # case1
            if line.lower().startswith("case"):

                current_case = []

                testcases[current_dim].append(current_case)

                continue

            try:
                nums = [int(x) for x in line.split()]
            except ValueError:
                continue

            if current_case is not None:
                current_case.extend(nums)
            else:
                testcases[current_dim].append(nums)

    # -----------------------
    # 修正長度
    # -----------------------

    for dim, cases in testcases.items():

        bit = int(dim[:-1])
        expected = 2 ** bit

        for i, case in enumerate(cases):

            if len(case) > expected:

                print(
                    f"{dim} case{i+1}",
                    case[expected:]
                )

                cases[i] = cases[i][:expected]

    return testcases


